/**
 * Find upazilas for a given district name or ID
 */
export function getUpazilasForDistrict(districtQuery: string): UpazilaItem[] {
  if (!districtQuery) return [];
  const q = districtQuery.trim().toLowerCase();
  
  const found = BANGLADESH_LOCATIONS.find(
    (d) =>
      d.id.toLowerCase() === q ||
      d.nameEn.toLowerCase() === q ||
      d.nameBn === districtQuery.trim()
  );

  return found ? found.upazilas : [];
}

/**
 * Check if the given district is Dhaka
 */
export function isDistrictInsideDhaka(districtQuery: string): boolean {
  if (!districtQuery) return false;
  const q = districtQuery.trim().toLowerCase();
  return q === 'dhaka' || q === 'ঢাকা';
}
